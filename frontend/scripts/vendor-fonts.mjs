#!/usr/bin/env node
/**
 * Bake the UI's Atkinson Hyperlegible faces into the build.
 *
 * Google's CSS2 API is asked for exactly the weights the app uses, then every
 * `@font-face` it answers with (latin and latin-ext subsets) is downloaded into
 * `public/fonts/` and rewritten as a local stylesheet at `src/styles/fonts.css`.
 * Vite copies `public/` verbatim into `dist/`, so the shipped bundle has no
 * runtime dependency on fonts.googleapis.com or fonts.gstatic.com and the nginx
 * CSP can stay `font-src 'self'`.
 *
 * Run from `frontend/`:
 *   node scripts/vendor-fonts.mjs
 *
 * Idempotent: it re-downloads and rewrites everything, so a rerun after a
 * Google Fonts family update is the whole upgrade path. Only the weights listed
 * in FAMILIES are vendored on purpose (see todo.md T5): 900 is not a real
 * Atkinson weight, so `font-black`/`font-weight: 900` keeps synthesising from
 * 800 exactly as it does today.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FONT_DIR = join(ROOT, 'public', 'fonts');
const CSS_FILE = join(ROOT, 'src', 'styles', 'fonts.css');

const FAMILIES = [
  { name: 'Atkinson Hyperlegible Next', slug: 'atkinson-next', weights: [400, 700, 800] },
  { name: 'Atkinson Hyperlegible Mono', slug: 'atkinson-mono', weights: [400, 500, 700] },
];

// A modern browser UA is what makes the CSS2 API answer with woff2 instead of
// ttf/otf, and with per-subset `unicode-range` blocks.
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

const apiUrl =
  'https://fonts.googleapis.com/css2?' +
  FAMILIES.map((f) => `family=${f.name.replaceAll(' ', '+')}:wght@${f.weights.join(';')}`).join('&') +
  '&display=swap';

const css = await (await fetch(apiUrl, { headers: { 'User-Agent': UA } })).text();
if (!css.includes('@font-face')) {
  throw new Error(`Google Fonts returned no @font-face blocks for ${apiUrl}:\n${css.slice(0, 400)}`);
}

// Each block is preceded by its subset comment, e.g. `/* latin *\/`.
const blockRe = /\/\*\s*([a-zA-Z-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g;
const faces = [];
for (const [, subset, body] of css.matchAll(blockRe)) {
  const family = /font-family:\s*'([^']+)'/.exec(body)?.[1];
  const weight = Number(/font-weight:\s*(\d+)/.exec(body)?.[1]);
  const url = /src:\s*url\(([^)]+)\)/.exec(body)?.[1];
  const unicodeRange = /unicode-range:\s*([^;]+);/.exec(body)?.[1];
  if (!family || !weight || !url || !unicodeRange) {
    throw new Error(`Unparsable @font-face block:\n${body}`);
  }
  const config = FAMILIES.find((f) => f.name === family);
  if (!config) throw new Error(`Unexpected family from Google Fonts: ${family}`);
  faces.push({ family, slug: config.slug, weight, subset, url, unicodeRange });
}

await mkdir(FONT_DIR, { recursive: true });

const written = [];
for (const face of faces) {
  const file = `${face.slug}-${face.subset}-${face.weight}.woff2`;
  const response = await fetch(face.url);
  if (!response.ok) throw new Error(`${response.status} fetching ${face.url}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  if (bytes.subarray(0, 4).toString('latin1') !== 'wOF2') {
    throw new Error(`${file} is not a woff2 payload (got ${bytes.subarray(0, 4).toString('latin1')})`);
  }
  await writeFile(join(FONT_DIR, file), bytes);
  written.push({ ...face, file, kib: (bytes.length / 1024).toFixed(1) });
}

// `latin` first so readers of the generated file see the primary subset on top.
const order = (a, b) =>
  FAMILIES.findIndex((f) => f.slug === a.slug) - FAMILIES.findIndex((f) => f.slug === b.slug) ||
  a.weight - b.weight ||
  (a.subset === 'latin' ? -1 : 1);

const rules = written
  .sort(order)
  .map(
    (f) => `@font-face {
  font-family: '${f.family}';
  font-style: normal;
  font-weight: ${f.weight};
  font-display: swap;
  src: url('/fonts/${f.file}') format('woff2');
  unicode-range: ${f.unicodeRange};
}`,
  )
  .join('\n\n');

const header = `/*
 * Generated by \`node scripts/vendor-fonts.mjs\` — do not edit by hand.
 *
 * Atkinson Hyperlegible Next (400/700/800) and Atkinson Hyperlegible Mono
 * (400/500/700), latin and latin-ext, self-hosted from Google Fonts under the
 * SIL Open Font License 1.1 (see public/fonts/OFL.txt). No request leaves the
 * origin for a font, which is what lets the nginx CSP keep \`font-src 'self'\`.
 *
 * Weights are limited to the ones the app actually asks for: 900 is not a real
 * Atkinson weight, so \`font-black\` / \`font-weight: 900\` synthesises from 800.
 */

`;

await writeFile(CSS_FILE, header + rules + '\n');

console.log(`vendored ${written.length} faces from ${apiUrl}`);
for (const f of written) console.log(`  ${f.file.padEnd(34)} ${f.kib.padStart(6)} KiB`);
console.log(`wrote ${CSS_FILE.slice(ROOT.length + 1)}`);
